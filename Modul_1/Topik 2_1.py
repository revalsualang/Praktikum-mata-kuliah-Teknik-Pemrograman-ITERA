print("=== Kalkulator Luas Lingkaran ===")

# Input jari-jari lingkaran
jari_jari = float(input("Masukkan jari-jari lingkaran (cm): "))

# Deklarasi konstanta pi
pi = 3.14

# Proses perhitungan
luas = pi * jari_jari ** 2

# Output hasil
print("\n--- Hasil Perhitungan ---")
print(f"Jari-jari : {jari_jari} cm")
print(f"Luas Lingkaran : {luas} cm^2")
